# vnum<TAB>mob type<TAB>rank<TAB>race flags, all database rows including zeros.
RACE_FLAGS_FILE = "gamedata/mob_race_flags.txt"
_dynamicBlob = None
_dynamicInfo = {}

def _DynamicInfo():
	global _dynamicBlob, _dynamicInfo
	try:
		# The client's root/__init__.py replaces open with its packed-file VFS.
		blob = open(RACE_FLAGS_FILE, "rb").read()
	except Exception:
		_dynamicBlob = None
		_dynamicInfo = {}
		return _dynamicInfo
	if blob == _dynamicBlob:
		return _dynamicInfo
	table = {}
	for line in blob.replace("\r", "\n").split("\n"):
		line = line.strip()
		if not line or line.startswith("#"):
			continue
		parts = line.split("\t")
		if len(parts) != 4:
			continue
		try:
			vnum, mobType, rank, flags = [int(value) for value in parts]
		except ValueError:
			continue
		if vnum > 0 and 0 <= mobType <= 255 and 0 <= rank <= 255 and flags >= 0:
			table[vnum] = (mobType, rank, flags & 2047)
	_dynamicBlob = blob
	_dynamicInfo = table
	return table

def GetInfo(vnum):
	return _DynamicInfo().get(vnum)

def Get(vnum):
	info = GetInfo(vnum)
	if info is not None:
		return info[2]
	# Newer executables may expose the actual loaded mob_proto flags.
	try:
		import nonplayer
		getter = getattr(nonplayer, "GetMonsterRaceFlag", None)
		if getter is not None:
			return int(getter(vnum)) & 2047
	except Exception:
		pass
	return RACE_FLAGS.get(vnum, 0)
